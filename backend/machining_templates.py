def _stages(plan, allowance):
    if plan == "R":
        return {"1": 0.0}
    if plan == "RF":
        sign = 1 if allowance > 0 else -1
        return {"1": float(allowance), "2": sign * MID_ALLOWANCE, "3": 0.0}
    if plan == "F":
        return {"3": 0.0}
    return {}


def _e(key, sig, x, y, text, plan, label, allowance=0.0, alt=()):
    """alt: 도면 개정으로 표기가 옮겨진 경우의 다른 기준 위치들 (예: 끼워맞춤 공차가 붙어 글자가 길어짐)"""
    return {"key": key, "sig": sig, "pos": (x, y), "alt_pos": tuple(alt), "text": text, "plan": plan,
            "label": label, "allowance": allowance, "stages": _stages(plan, allowance)}


