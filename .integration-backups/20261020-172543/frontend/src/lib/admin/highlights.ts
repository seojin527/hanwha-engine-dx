/** 치수는 글자 중심, 기하공차는 줄마다 있는 번호판 위치로 선을 찾는다 */
const DIM_RADIUS = MATCH_RADIUS;
const GDT_RADIUS = 130;

/**
 * 항목 위치로 강조할 선을 찾는다. 가까운 선 위치가 없으면 undefined (강조 없음).
 * - 치수(DIMENSION): position(글자 중심)과 선 위치를 비교한다.
 * - 기하공차(GDT): 한 프레임의 두 줄이 같은 position 을 가지므로 줄마다 다른 label_anchor 로 비교한다.
 */
export function findHighlight(item: {
  category: string;
  position: { x: number; y: number };
  label_anchor?: { x: number; y: number };
}): Point[][] | undefined {
  const isGdt = item.category === "GDT";
  const at = isGdt ? item.label_anchor ?? item.position : item.position;
  const radius = isGdt ? GDT_RADIUS : DIM_RADIUS;
  let best: { slot: HighlightSlot; distance: number } | null = null;
  for (const slot of HIGHLIGHT_SLOTS) {
    if (slot.name.startsWith("GD&T") !== isGdt) continue;
    for (const [x, y] of slot.anchors) {
      const distance = Math.hypot(at.x - x, at.y - y);
      if (distance <= radius && (!best || distance < best.distance)) best = { slot, distance };
    }
  }
  return best?.slot.lines.map((line) => line.map(([x, y]) => ({ x, y })));
}
